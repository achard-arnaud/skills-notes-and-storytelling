import copy
from pathlib import Path
import sys
import unittest

ROOT=Path(__file__).resolve().parents[1]
sys.path[:0]=[str(ROOT),str(ROOT/'tests')]
from analysis_writing import prepare_analysis_writing, plan_analysis_writing_revision
from test_adoption import sample, run_method
from writing import study_hash
from render import render_study


def inputs():
    study,brief,plan,m,_=sample()
    env=run_method(study,brief,plan,m)['envelope']
    ref={'analysis_ref':'A1','finding_index':0}
    synthesis=dict(schema_version='1.0',study_ref=study['id'],envelope_revision=study_hash(env),
                   candidate_thesis={'text':'Declared weekly adoption is 30%; retention remains outside scope.', 'finding_refs':[ref]},
                   observations=[ref],claim_disposition=[{'claim_ref':c['id'],'state':'included','reason':''} for c in study['claims']])
    topology={'sections':[dict(id='B1',title='What usage is documented?',analysis_refs=['A1'],claim_ids=[],pillar_ids=[])]}
    return study,brief,plan,env,synthesis,topology


def prepare(args,perspective='product'):
    study,brief,plan,env,synthesis,topology=args
    return prepare_analysis_writing(study,env,plan,brief,synthesis,topology,perspective=perspective)


class AnalysisWritingTests(unittest.TestCase):
    def test_consumes_actual_analysis_with_evidence_only_bootstrap(self):
        args=inputs();before=copy.deepcopy(args)
        result=prepare(args)
        self.assertEqual(['C1','C2','C3'],result['study']['sections'][0]['claim_ids'])
        self.assertNotIn('analyses',result['study'])
        self.assertNotIn('analysis_refs',result['study']['sections'][0])
        self.assertFalse(result['packet']['reader_prose_loaded'])
        ctx=result['analysis_context']
        self.assertEqual(['A1'],ctx['bindings'][0]['analysis_refs'])
        self.assertIn('30.00%',ctx['resolved_findings'][0]['statement'])
        self.assertEqual('inference',ctx['resolved_findings'][0]['status'])
        self.assertFalse(ctx['human_approval'])
        self.assertEqual(before,args)
        # Supplied prose consumes the resolved finding; no prose is generated by the adapter.
        result['study']['sections'][0]['paragraphs']=[dict(id='P1',text=ctx['resolved_findings'][0]['statement'],claim_ids=['C1','C2','C3'],pillar_ids=[],review={'evidence':False,'editorial':False})]
        self.assertIn('30.00%',render_study(result['study']))

    def test_two_perspectives_keep_identical_evidence_and_analysis(self):
        args=inputs();product=prepare(args)
        changed=copy.deepcopy(args);changed[5]['sections'][0]['title']='What does this imply for the business model?'
        business=prepare(changed,'business')
        for key in ('sources','fragments','claims','relations'):
            self.assertEqual(product['study'][key],business['study'][key])
        self.assertEqual(product['analysis_context']['envelope_revision'],business['analysis_context']['envelope_revision'])
        self.assertNotEqual(product['study']['sections'][0]['title'],business['study']['sections'][0]['title'])

    def test_stale_or_foreign_synthesis_refs_and_versions_rejected(self):
        for key,value in [('schema_version','2.0'),('study_ref','foreign'),('envelope_revision','0'*64),
                          ('observations',[{'analysis_ref':'A404','finding_index':0}]),
                          ('observations',[{'analysis_ref':'A1','finding_index':9}])]:
            args=inputs();args[4][key]=value
            with self.assertRaises(ValueError):prepare(args)
        args=inputs();args[4]['candidate_thesis']['finding_refs']=[{'analysis_ref':'A1','finding_index':3}]
        with self.assertRaises(ValueError):prepare(args)

    def test_every_claim_requires_consistent_disposition(self):
        for change in ('missing','duplicate','omitted_without_reason','omitted_but_used'):
            args=inputs();coverage=args[4]['claim_disposition']
            if change=='missing':coverage.pop()
            elif change=='duplicate':coverage.append(copy.deepcopy(coverage[0]))
            else:
                coverage[0]['state']='omitted'
                coverage[0]['reason']='Outside scope' if change.endswith('used') else ''
            with self.assertRaises(ValueError):prepare(args)

    def test_unknown_empty_or_unsupported_block_refs_rejected(self):
        for key,value in [('analysis_refs',['foreign']),('claim_ids',['foreign']),('pillar_ids',['foreign']),
                          ('paragraphs',[{'text':'old reader'}])]:
            args=inputs();args[5]['sections'][0][key]=value
            with self.assertRaises(ValueError):prepare(args)
        args=inputs();args[4]['observations']=[];args[4]['candidate_thesis']['finding_refs']=[]
        with self.assertRaises(ValueError):prepare(args)

    def test_selected_findings_cannot_disappear_from_blocks(self):
        args=inputs();args[5]['sections'][0]['analysis_refs']=[];args[5]['sections'][0]['claim_ids']=['C1','C2','C3']
        with self.assertRaises(ValueError):prepare(args)
        for index in (-1, True, 0.5):
            args=inputs();args[4]['observations'][0]['finding_index']=index
            with self.assertRaises(ValueError):prepare(args)
        args=inputs();args[4]['observations'][0]['finding_index']=0.0
        self.assertEqual(1,len(prepare(args)['analysis_context']['resolved_findings']))

    def test_partial_analysis_keeps_question_and_gaps_without_findings(self):
        args=list(inputs());study,brief,plan,env,syn,top=args
        row=env['analyses'][0];row.update(state='partial',needs_research=True,findings=[],unknowns=['No denominator'])
        syn['observations']=[];syn['candidate_thesis']={'text':'The question remains open','finding_refs':[]};syn['envelope_revision']=study_hash(env)
        top['sections'][0]['claim_ids']=['C1','C2','C3']
        result=prepare(args)
        self.assertEqual([],result['analysis_context']['resolved_findings'])
        self.assertTrue(result['analysis_context']['gaps'])
        self.assertEqual('partial',result['analysis_context']['analysis_states']['A1'])

    def test_analysis_output_invalidates_only_bound_section_and_paragraphs(self):
        args=inputs();prepared=prepare(args);study=prepared['study'];env=args[3];ctx=prepared['analysis_context']
        study['sections'][0]['paragraphs']=[dict(id='P1',text='Candidate',claim_ids=['C1'],pillar_ids=[],review={})]
        study['sections'].append(dict(id='B2',title='Independent',claim_ids=[],pillar_ids=[],paragraphs=[dict(id='P2',text='Independent',claim_ids=[],pillar_ids=[],review={})]))
        receipt=plan_analysis_writing_revision(study,env,ctx,['A1'],expected_study_hash=study_hash(study),expected_envelope_hash=study_hash(env))
        self.assertEqual(['B1'],receipt['analysis_invalidated_section_ids'])
        self.assertEqual(['P1'],receipt['analysis_invalidated_paragraph_ids'])
        self.assertNotIn('P2',receipt['writing']['paragraph_ids'])
        source=plan_analysis_writing_revision(study,env,ctx,['SRC1'],expected_study_hash=study_hash(study),expected_envelope_hash=study_hash(env))
        self.assertEqual(['B1'],source['analysis_invalidated_section_ids'])
        self.assertNotIn('P2',source['writing']['paragraph_ids'])
        self.assertIn('P1',receipt['writing']['evidence_invalidated_paragraph_ids'])
        layout=plan_analysis_writing_revision(study,env,ctx,['P1'],expected_study_hash=study_hash(study),expected_envelope_hash=study_hash(env))
        self.assertEqual([],layout['invalidate_analysis_ids'])

    def test_stale_context_and_unknown_binding_refused(self):
        args=inputs();prepared=prepare(args);study=prepared['study'];env=args[3]
        for field,value in [('envelope_revision','0'*64),('bindings',[{'section_id':'foreign','analysis_refs':['A1'],'claim_ids':[]}])]:
            ctx=copy.deepcopy(prepared['analysis_context']);ctx[field]=value
            with self.assertRaises(ValueError):plan_analysis_writing_revision(study,env,ctx,['A1'],expected_study_hash=study_hash(study),expected_envelope_hash=study_hash(env))


if __name__=='__main__':unittest.main()
